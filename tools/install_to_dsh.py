#!/usr/bin/env python3
"""Install the ProtForge skill set into a local DeepSeek Harness (DSH) home.

DSH discovers user-level skills from ``$DSH_HOME/skills`` (see
``@deepseek-ai/dsh-skill-filesystem``: ``join(this.dshHome, "skills")``). This
script copies every ProtForge skill directory there and rewrites the parts of
each ``SKILL.md`` that assume the MiniMax Code plugin runtime:

* ``${PLUGIN_DIR}``      -> the absolute plugin root (DSH has no plugin context)
* ``bash "<script>"``    -> pinned Git Bash, because bare ``bash`` on Windows is
                            the WSL launcher and cannot open ``C:/...`` paths
* ``\\`` continuations    -> joined onto one line, because ``\\`` continues a
                            command in bash but not in PowerShell
* ``<tools-dir>``        -> the real WSL tools directory for the MSA skills
* ``<windows-home>/``     -> the WSL view of the same path (``/mnt/c/...``)

The install is generated, not hand-maintained: edit the plugin source, then
re-run this script. Re-running only replaces the skill directories this script
recorded in its manifest, so unrelated skills in the same DSH home are untouched.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

PLUGIN_DIR = Path(r"C:\Users\dy120\.minimax\plugins\protforge")
GIT_BASH = "C:/Program Files/Git/bin/bash.exe"
# WSL view of the ProtForge MSA helpers; kept out of the plugin tree on purpose.
TOOLS_DIR_WSL = "/mnt/e/oih/oih-upgrade/02-newtools"
MANIFEST_NAME = ".protforge-dsh-install.json"

# `> Note: `${PLUGIN_DIR}` ... substitute before invoking the ... command below.`
NOTE_RE = re.compile(
    r"^> Note: `\$\{PLUGIN_DIR\}`.+?substitute before invoking the[^\n]*\n",
    re.MULTILINE | re.DOTALL,
)
BASH_FENCE_RE = re.compile(r"^(```bash\n)(.*?)(^```\s*$)", re.MULTILINE | re.DOTALL)
CONTINUATION_RE = re.compile(r"\\\n[ \t]*")
BASH_COMMAND_RE = re.compile(r'(?m)^([ \t]*)bash[ \t]+(?=")')

MACHINE_NOTE = """> **Running this on this machine (DSH install).** Commands below are
> written for **PowerShell**, where `&` is the call operator. Bare `bash` on
> Windows is the WSL launcher and cannot open `C:/...` paths, so every runner
> goes through Git Bash by absolute path — keep the `&` prefix, and drop it if
> you are in a bash shell. Plugin root: `{plugin_dir}`.
> Generated by `tools/install_to_dsh.py` — edit the plugin source and re-run it
> instead of editing this file."""


def dsh_home(explicit: str | None) -> Path:
    """Resolve DSH_HOME: the Beta desktop uses `.dsh-beta`, stable uses `.dsh`."""
    if explicit:
        return Path(explicit)
    for name in (".dsh-beta", ".dsh"):
        candidate = Path.home() / name
        if candidate.is_dir():
            return candidate
    return Path.home() / ".dsh-beta"


def rewrite_bash_fence(match: re.Match[str]) -> str:
    """Make one ```bash block valid in PowerShell as well as bash."""
    opener, body, closer = match.group(1), match.group(2), match.group(3)
    body = CONTINUATION_RE.sub(" ", body)
    body = BASH_COMMAND_RE.sub(r'\1& "' + GIT_BASH + '" ', body)
    return opener + body + closer


def rewrite_skill_md(text: str, plugin_root: str) -> str:
    text = NOTE_RE.sub(MACHINE_NOTE.format(plugin_dir=plugin_root) + "\n", text, count=1)
    text = BASH_FENCE_RE.sub(rewrite_bash_fence, text)
    text = text.replace("<tools-dir>", TOOLS_DIR_WSL)
    text = re.sub(
        r"<windows-home>(?=[^\n]*?\.minimax/plugins/protforge)",
        "/mnt/c/Users/" + Path.home().name,
        text,
    )
    text = text.replace("${PLUGIN_DIR}", plugin_root)
    return text


def install(skills_src: Path, dest_root: Path, dry_run: bool) -> int:
    plugin_root = skills_src.parent.as_posix()
    skills = sorted(p for p in skills_src.iterdir() if (p / "SKILL.md").is_file())
    if not skills:
        print(f"no skills found under {skills_src}", file=sys.stderr)
        return 1

    manifest_path = dest_root / MANIFEST_NAME
    previous: list[str] = []
    if manifest_path.is_file():
        previous = json.loads(manifest_path.read_text(encoding="utf-8")).get("skills", [])

    dest_root.mkdir(parents=True, exist_ok=True)
    installed: list[str] = []
    for skill in skills:
        target = dest_root / skill.name
        if dry_run:
            print(f"[dry-run] {skill.name} -> {target}")
            installed.append(skill.name)
            continue
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(skill, target, ignore=shutil.ignore_patterns("__pycache__"))
        skill_md = target / "SKILL.md"
        skill_md.write_text(
            rewrite_skill_md(skill_md.read_text(encoding="utf-8"), plugin_root),
            encoding="utf-8",
            newline="\n",
        )
        installed.append(skill.name)

    stale = [name for name in previous if name not in installed and name.startswith("protforge-")]
    for name in stale:
        stale_dir = dest_root / name
        if stale_dir.is_dir():
            if dry_run:
                print(f"[dry-run] remove stale {name}")
            else:
                shutil.rmtree(stale_dir)

    if not dry_run:
        manifest_path.write_text(
            json.dumps(
                {
                    "source": skills_src.as_posix(),
                    "plugin_root": plugin_root,
                    "skills": installed,
                },
                indent=2,
            ),
            encoding="utf-8",
            newline="\n",
        )

    print(f"DSH home : {dest_root}")
    print(f"Plugin   : {plugin_root}")
    print(f"Skills   : {len(installed)} installed" + (f", {len(stale)} stale removed" if stale else ""))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plugin-dir", default=str(PLUGIN_DIR))
    parser.add_argument("--dsh-home", default=None, help="override DSH_HOME")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    skills_src = Path(args.plugin_dir) / "skills"
    if not skills_src.is_dir():
        print(f"plugin skills not found: {skills_src}", file=sys.stderr)
        return 1
    return install(skills_src, dsh_home(args.dsh_home) / "skills", args.dry_run)


if __name__ == "__main__":
    raise SystemExit(main())
